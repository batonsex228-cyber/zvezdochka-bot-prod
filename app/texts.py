def escalation_text(question: str, reason: str, *, delivered: bool) -> str:
    """Return a parent-facing handoff message without pretending the bot knows live availability."""
    if not delivered:
        return ESCALATED_NO_CHANNEL

    if reason != "dynamic_availability":
        return ESCALATED

    n = (question or "").lower().replace("ё", "е")
    if "бесед" in n:
        what = "свободна ли беседка на эту дату"
    elif "корпус" in n:
        what = "свободен ли корпус на эту дату"
    elif "домик" in n:
        what = "свободен ли домик на эту дату"
    elif any(k in n for k in ["путев", "мест", "смен"]):
        return (
            "Сейчас уточню у специалиста актуальное наличие мест 💛\n\n"
            "Я уже <b>отправил Ваш запрос</b>. Как только специалист проверит наличие путёвок/мест, "
            "ответ придёт прямо сюда. Повторно писать вопрос не нужно."
        )
    else:
        what = "свободна ли нужная дата"

    return (
        f"Сейчас уточню у специалиста, {what} 💛\n\n"
        "Я уже <b>отправил Ваш запрос</b>. Как только специалист проверит бронирование, "
        "ответ придёт прямо сюда. Повторно писать вопрос не нужно."
    )
